"""Manages long-lived auth proxies and SSH reverse tunnels associated with XPU instances.

Provides daemon supervision, state tracking, and remote profile configuration.
"""

import argparse
import json
import os
import shlex
import shutil
import signal
import subprocess
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from xpu_shell.auth_proxy import create_auth_proxy
from xpu_shell.ssh_runner import build_ssh_cmd


def get_proxy_base_dir() -> Path:
  custom_dir = os.environ.get("XPU_SHELL_CONFIG_DIR") or os.environ.get("RUNPOD_SHELL_CONFIG_DIR")
  if custom_dir:
    base = Path(custom_dir).expanduser()
  else:
    base = Path.home() / ".config" / "xpu_shell"
  return base / "proxies"


def get_proxy_dir(pod_id: str) -> Path:
  return get_proxy_base_dir() / str(pod_id)


def is_pid_alive(pid: int) -> bool:
  if pid <= 0:
    return False
  try:
    os.kill(pid, 0)
    return True
  except OSError:
    return False


def get_active_proxy_info(pod_id: str) -> Optional[Dict[str, Any]]:
  pdir = get_proxy_dir(pod_id)
  meta_file = pdir / "meta.json"
  if not meta_file.exists():
    return None

  try:
    meta = json.loads(meta_file.read_text())
    pid = int(meta.get("pid", 0))
    if is_pid_alive(pid):
      return meta
    else:
      # Process died, clean up stale state
      shutil.rmtree(pdir, ignore_errors=True)
      return None
  except Exception:
    return None


def list_active_proxies() -> List[Dict[str, Any]]:
  base = get_proxy_base_dir()
  if not base.exists():
    return []

  active = []
  for p in base.iterdir():
    if p.is_dir():
      info = get_active_proxy_info(p.name)
      if info:
        active.append(info)
  return active


def deploy_remote_profile(
  host: str,
  port: int,
  env_vars: Dict[str, str],
  private_key_path: Optional[str] = None,
  ssh_config_path: Optional[str] = None
) -> None:
  """Writes /etc/profile.d/xpu_proxy.sh on remote pod for global environment availability."""
  if not env_vars:
    return

  lines = ["# Generated by xpu-shell auth proxy"]
  for k, v in env_vars.items():
    lines.append(f"export {k}={shlex.quote(str(v))}")
  content = "\n".join(lines) + "\n"

  remote_cmd = (
    f"mkdir -p /etc/profile.d && "
    f"cat << 'EOF' > /etc/profile.d/xpu_proxy.sh\n{content}EOF\n"
    f"chmod 644 /etc/profile.d/xpu_proxy.sh"
  )
  cmd = build_ssh_cmd(
    host=host,
    port=port,
    remote_command=remote_cmd,
    private_key_path=private_key_path,
    ssh_config_path=ssh_config_path
  )
  try:
    subprocess.run(cmd, capture_output=True, timeout=15)
  except Exception:
    pass


def remove_remote_profile(
  host: str,
  port: int,
  private_key_path: Optional[str] = None,
  ssh_config_path: Optional[str] = None
) -> None:
  """Removes /etc/profile.d/xpu_proxy.sh on remote pod."""
  cmd = build_ssh_cmd(
    host=host,
    port=port,
    remote_command="rm -f /etc/profile.d/xpu_proxy.sh",
    private_key_path=private_key_path,
    ssh_config_path=ssh_config_path
  )
  try:
    subprocess.run(cmd, capture_output=True, timeout=15)
  except Exception:
    pass


def start_proxy_for_pod(
  pod_id: str,
  host: str,
  port: int,
  remote_port: int = 8080,
  private_key_path: Optional[str] = None,
  ssh_config_path: Optional[str] = None,
  allow_write: Optional[str] = None,
  verbose: bool = False
) -> Dict[str, Any]:
  """Spawns a background proxy daemon and SSH reverse tunnel for the given pod."""
  existing = get_active_proxy_info(pod_id)
  if existing:
    if verbose:
      print(f"Auth proxy is already active for pod {pod_id} on port {existing.get('remote_port')}", file=sys.stderr)
    return existing

  pdir = get_proxy_dir(pod_id)
  pdir.mkdir(parents=True, exist_ok=True)
  log_file = pdir / "proxy.log"

  worker_cmd = [
    sys.executable,
    "-m", "xpu_shell.proxy_manager",
    "worker",
    "--pod-id", str(pod_id),
    "--host", str(host),
    "--port", str(port),
    "--remote-port", str(remote_port)
  ]
  if private_key_path:
    worker_cmd.extend(["--private-key-path", str(private_key_path)])
  if ssh_config_path:
    worker_cmd.extend(["--ssh-config-path", str(ssh_config_path)])
  if allow_write:
    worker_cmd.extend(["--allow-write", str(allow_write)])

  with open(log_file, "a") as log_fd:
    proc = subprocess.Popen(
      worker_cmd,
      stdin=subprocess.DEVNULL,
      stdout=log_fd,
      stderr=subprocess.STDOUT,
      start_new_session=True,
      close_fds=True
    )

  # Wait for meta.json to be written
  meta_file = pdir / "meta.json"
  start_time = time.time()
  while time.time() - start_time < 8.0:
    if meta_file.exists():
      try:
        meta = json.loads(meta_file.read_text())
        if is_pid_alive(meta.get("pid", 0)):
          # Also deploy remote profile so interactive SSH has the environment immediately
          env_vars = meta.get("env", {})
          if env_vars:
            deploy_remote_profile(
              host=host,
              port=port,
              env_vars=env_vars,
              private_key_path=private_key_path,
              ssh_config_path=ssh_config_path
            )
          return meta
      except Exception:
        pass
    if proc.poll() is not None:
      break
    time.sleep(0.2)

  # If failed to start
  err_msg = ""
  if log_file.exists():
    err_msg = log_file.read_text().strip()
  shutil.rmtree(pdir, ignore_errors=True)
  raise RuntimeError(f"Failed to start auth proxy daemon for pod {pod_id}. {err_msg}")


def stop_proxy_for_pod(
  pod_id: str,
  host: Optional[str] = None,
  port: Optional[int] = None,
  private_key_path: Optional[str] = None,
  ssh_config_path: Optional[str] = None,
  verbose: bool = False
) -> bool:
  """Stops the proxy daemon for the given pod and removes remote profile."""
  info = get_active_proxy_info(pod_id)
  pdir = get_proxy_dir(pod_id)

  target_host = host or (info.get("host") if info else None)
  target_port = port or (info.get("port") if info else None)
  if target_host and target_port:
    remove_remote_profile(
      host=target_host,
      port=int(target_port),
      private_key_path=private_key_path,
      ssh_config_path=ssh_config_path
    )

  if not info:
    shutil.rmtree(pdir, ignore_errors=True)
    return False

  pid = info.get("pid")
  if pid and is_pid_alive(pid):
    try:
      os.kill(pid, signal.SIGTERM)
      # Wait up to 3 seconds for clean exit
      for _ in range(15):
        if not is_pid_alive(pid):
          break
        time.sleep(0.2)
      if is_pid_alive(pid):
        os.kill(pid, signal.SIGKILL)
    except OSError:
      pass

  shutil.rmtree(pdir, ignore_errors=True)
  return True


def run_worker(args: argparse.Namespace) -> None:
  """Entrypoint for the background proxy worker process."""
  pod_id = args.pod_id
  host = args.host
  port = int(args.port)
  remote_port = int(args.remote_port)
  private_key_path = getattr(args, "private_key_path", None)
  ssh_config_path = getattr(args, "ssh_config_path", None)
  allow_write = getattr(args, "allow_write", None)

  pdir = get_proxy_dir(pod_id)
  pdir.mkdir(parents=True, exist_ok=True)
  meta_file = pdir / "meta.json"
  (pdir / "pid").write_text(str(os.getpid()))

  # 1. Initialize and start the local HTTP auth proxy
  proxy = create_auth_proxy(allow_write=allow_write)
  proxy.start()

  remote_env = proxy.get_remote_env(remote_host="127.0.0.1", remote_port=remote_port)

  # 2. Build the SSH reverse tunnel command
  tunnel_cmd = build_ssh_cmd(
    host=host,
    port=port,
    private_key_path=private_key_path,
    ssh_config_path=ssh_config_path
  )
  # Replace standard execution options with background tunnel flags
  # Insert -N and reverse tunnel arguments
  tunnel_cmd.insert(1, "-N")
  tunnel_cmd.insert(2, "-o")
  tunnel_cmd.insert(3, "ExitOnForwardFailure=yes")
  tunnel_cmd.insert(4, "-o")
  tunnel_cmd.insert(5, "ServerAliveInterval=30")
  tunnel_cmd.insert(6, "-o")
  tunnel_cmd.insert(7, "ServerAliveCountMax=3")
  tunnel_cmd.insert(8, "-R")
  tunnel_cmd.insert(9, f"{remote_port}:127.0.0.1:{proxy.port}")

  tunnel_proc = subprocess.Popen(
    tunnel_cmd,
    stdin=subprocess.DEVNULL,
    stdout=subprocess.DEVNULL,
    stderr=subprocess.PIPE
  )

  # Check if tunnel failed immediately (e.g. port already bound on remote)
  time.sleep(1.0)
  if tunnel_proc.poll() is not None:
    err = tunnel_proc.stderr.read().decode("utf-8") if tunnel_proc.stderr else ""
    proxy.stop()
    sys.exit(f"Tunnel process exited with code {tunnel_proc.returncode}: {err}")

  # 3. Write metadata file
  meta = {
    "pid": os.getpid(),
    "pod_id": pod_id,
    "host": host,
    "port": port,
    "local_port": proxy.port,
    "remote_port": remote_port,
    "started_at": int(time.time()),
    "routes": [r.prefix for r in proxy.routes],
    "env": remote_env
  }
  meta_file.write_text(json.dumps(meta, indent=2))

  # 4. Handle clean termination
  def handle_term(signum, frame):
    try:
      if tunnel_proc.poll() is None:
        tunnel_proc.terminate()
    except Exception:
      pass
    proxy.stop()
    shutil.rmtree(pdir, ignore_errors=True)
    sys.exit(0)

  signal.signal(signal.SIGTERM, handle_term)
  signal.signal(signal.SIGINT, handle_term)

  # 5. Supervision loop: keep running while tunnel is healthy
  try:
    while True:
      ret = tunnel_proc.poll()
      if ret is not None:
        break
      time.sleep(2.0)
  finally:
    handle_term(None, None)


def main():
  parser = argparse.ArgumentParser(description="XPU Shell Proxy Manager Worker")
  subparsers = parser.add_subparsers(dest="command")

  worker_parser = subparsers.add_parser("worker")
  worker_parser.add_argument("--pod-id", required=True)
  worker_parser.add_argument("--host", required=True)
  worker_parser.add_argument("--port", required=True, type=int)
  worker_parser.add_argument("--remote-port", default=8080, type=int)
  worker_parser.add_argument("--private-key-path", default=None)
  worker_parser.add_argument("--ssh-config-path", default=None)
  worker_parser.add_argument("--allow-write", default=None)

  args = parser.parse_args()
  if args.command == "worker":
    run_worker(args)
  else:
    parser.print_help()


if __name__ == "__main__":
  main()
